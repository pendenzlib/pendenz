package io.github.d4niella.pendenz.schema

import java.util.UUID as JavaUuid

/**
 * The type of the id column, and who generates an id when the caller gives
 * none. Part of the [TaskTable] mapping, see ADR 0007.
 *
 * Sealed on purpose: the two constants cover `bigint` and `uuid` keys. The
 * members the stores need are internal, so a new kind is an addition to the
 * core, not an extension point.
 */
public sealed class IdType<ID : Any> {
    /** The column definition without the name, as the DDL generator prints it. */
    internal abstract val columnDefinition: String

    /** The bare SQL type, for function parameters. */
    internal abstract val sqlType: String

    /** The class JDBC reads the column as. */
    internal abstract val javaType: Class<ID>

    /** An id made on the client, or null when the database generates it. */
    internal abstract fun generate(): ID?

    /** An id for a store without a database, derived from a counter. */
    internal abstract fun fromSequence(sequence: Long): ID

    private object Bigint : IdType<Long>() {
        override val columnDefinition = "bigint GENERATED BY DEFAULT AS IDENTITY"
        override val sqlType = "bigint"
        override val javaType: Class<Long> = Long::class.javaObjectType

        override fun generate(): Long? = null

        override fun fromSequence(sequence: Long): Long = sequence

        override fun toString() = "IdType.BIGINT"
    }

    private object Uuid : IdType<JavaUuid>() {
        override val columnDefinition = "uuid DEFAULT gen_random_uuid()"
        override val sqlType = "uuid"
        override val javaType: Class<JavaUuid> = JavaUuid::class.java

        override fun generate(): JavaUuid = JavaUuid.randomUUID()

        override fun fromSequence(sequence: Long): JavaUuid = generate()

        override fun toString() = "IdType.UUID"
    }

    public companion object {
        /** A `bigint` identity column. The database generates ids unless the caller supplies one. */
        @JvmField
        public val BIGINT: IdType<Long> = Bigint

        /** A `uuid` column. The client generates a random id unless the caller supplies one. */
        @JvmField
        public val UUID: IdType<JavaUuid> = Uuid
    }
}
