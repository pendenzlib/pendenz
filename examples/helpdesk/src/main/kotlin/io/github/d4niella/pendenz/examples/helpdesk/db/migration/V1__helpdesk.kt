package io.github.d4niella.pendenz.examples.helpdesk.db.migration

import io.github.d4niella.pendenz.examples.helpdesk.Helpdesk
import io.github.d4niella.pendenz.schema.PostgresDdl
import io.github.d4niella.pendenz.schema.PostgresOperatorDdl
import org.flywaydb.core.api.migration.BaseJavaMigration
import org.flywaydb.core.api.migration.Context

/**
 * The ticket tables, the task table with the payload columns of the three
 * task types, and the operator views and functions, so that a person can
 * approve an escalation with `SELECT helpdesk_task_approve(id, version, 'name')`.
 */
@Suppress("ClassName") // Flyway derives version and description from the name
class V1__helpdesk : BaseJavaMigration() {
    override fun migrate(context: Context) {
        context.connection.createStatement().use { statement ->
            statement.execute(
                """
                CREATE TABLE ticket (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    customer text NOT NULL,
                    subject text NOT NULL,
                    body text NOT NULL,
                    status text NOT NULL DEFAULT 'OPEN',
                    priority text NOT NULL DEFAULT 'NORMAL',
                    escalated_to text
                );
                CREATE TABLE ticket_reply (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    ticket_id bigint NOT NULL REFERENCES ticket (id),
                    text text NOT NULL,
                    sent_at timestamptz NOT NULL DEFAULT now()
                );
                """.trimIndent(),
            )
            statement.execute(
                PostgresDdl.createTable(
                    Helpdesk.TABLE,
                    Helpdesk.REPLY,
                    Helpdesk.SEND_REPLY,
                    Helpdesk.ESCALATE,
                    Helpdesk.PRIORITISE,
                ),
            )
            statement.execute(PostgresOperatorDdl.views(Helpdesk.TABLE))
            statement.execute(PostgresOperatorDdl.functions(Helpdesk.TABLE))
        }
    }
}
