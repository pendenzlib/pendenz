package db.migration

import io.github.pendenzlib.examples.spring.Billing
import io.github.pendenzlib.schema.PostgresDdl
import io.github.pendenzlib.schema.PostgresOperatorDdl
import org.flywaydb.core.api.migration.BaseJavaMigration
import org.flywaydb.core.api.migration.Context

/**
 * The invoice table, the task table with the mail's payload column, and
 * the views and functions an operator uses: `billing_task_failures`,
 * `billing_task_restart(id, version)` and the rest. In `db.migration`,
 * where Spring Boot's Flyway looks by default.
 */
@Suppress("ClassName") // Flyway derives version and description from the name
class V1__shop : BaseJavaMigration() {
    override fun migrate(context: Context) {
        context.connection.createStatement().use { statement ->
            statement.execute(
                """
                CREATE TABLE invoice (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    customer text NOT NULL,
                    amount numeric(12, 2) NOT NULL,
                    sent_at timestamptz
                );
                """.trimIndent(),
            )
            statement.execute(PostgresDdl.createTable(Billing.TABLE, Billing.SEND_INVOICE))
            statement.execute(PostgresOperatorDdl.views(Billing.TABLE))
            statement.execute(PostgresOperatorDdl.functions(Billing.TABLE))
        }
    }
}
