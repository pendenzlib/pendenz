package io.github.d4niella.pendenz.examples.catalog.db.migration

import io.github.d4niella.pendenz.examples.catalog.Catalog
import io.github.d4niella.pendenz.schema.PostgresDdl
import io.github.d4niella.pendenz.schema.PostgresOperatorDdl
import org.flywaydb.core.api.migration.BaseJavaMigration
import org.flywaydb.core.api.migration.Context

/**
 * The product table, the task table with the classification's payload
 * column, the cycle and resource limit tables, and the views and functions
 * an operator uses: `catalog_cycle_progress`, `catalog_task_needs_human`,
 * `catalog_task_restart(id, version)` and the rest.
 */
@Suppress("ClassName") // Flyway derives version and description from the name
class V1__catalog : BaseJavaMigration() {
    override fun migrate(context: Context) {
        context.connection.createStatement().use { statement ->
            statement.execute(
                """
                CREATE TABLE product (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name text NOT NULL,
                    description text,
                    recalled boolean NOT NULL DEFAULT false,
                    -- What a person would say; the handler never reads it, the report compares against it.
                    expected_category text NOT NULL
                );
                """.trimIndent(),
            )
            statement.execute(PostgresDdl.createTable(Catalog.TABLE, Catalog.CLASSIFY))
            statement.execute(PostgresDdl.createCycleTable(Catalog.CYCLES))
            statement.execute(PostgresDdl.cycleProgressView(Catalog.TABLE, Catalog.CYCLES))
            statement.execute(PostgresDdl.createResourceLimitTable(Catalog.LIMITS))
            statement.execute(PostgresOperatorDdl.views(Catalog.TABLE))
            statement.execute(PostgresOperatorDdl.functions(Catalog.TABLE, Catalog.CYCLES))
        }
    }
}
